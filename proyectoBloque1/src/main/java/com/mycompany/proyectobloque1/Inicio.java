    private void btnWindowsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnWindowsActionPerformed
        // TODO add your handling code here:
        try {
            String comando = "(Get-CimInstance Win32_OperatingSystem).Caption";
            ProcessBuilder pb = new ProcessBuilder("powershell.exe", "/c", comando);
            Process proceso = pb.start();
            
            BufferedReader br = new BufferedReader(new InputStreamReader(proceso.getInputStream()));
            String linea;
            String info = "";
            
            while((linea = br.readLine())!=null){
                info = info+linea+"\n";
            }
            
            JOptionPane.showMessageDialog(this, info);
        } catch (IOException e) {
        }
        HistorialTexto.historial = HistorialTexto.historial + "[" +LocalDateTime.now()+ "]\t" + "VERSION DE WINDOWS\n" ;
        try {
            FileWriter fw = new FileWriter("historial.txt", true);
            fw.write("[" +LocalDateTime.now()+ "];" + "VERSION DE WINDOWS\n");
            fw.close();
        } catch (Exception e) {
        }
    }//GEN-LAST:event_btnWindowsActionPerformed

